#!/usr/bin/env python3
"""Generate color texture sets for Choice block textures vanilla already locks.

Vanilla bedrock-samples v1.26.60.5 ships a .texture_set.json beside most block
colors. Microsoft documents that a texture set can only reference images in its
own pack, and that a higher pack's PNG does not replace that reference. Sets
do not merge. A Choice color PNG alone stays hidden under Vibrant Visuals.

This writes a texture set next to each matching Choice block color. The set
points color at that file and pins the documented fully-rough MERS so the
replacement does not leave roughness unspecified. Classic/Fancy use only the
color layer.

Re-run from the repo root after adding block colors:

    python3 tools/choice_vv/generate_block_texture_sets.py

Refresh the vanilla filename list from a GitHub git-tree JSON of
resource_pack/textures/blocks (recursive) when the stable tag moves:

    python3 tools/choice_vv/generate_block_texture_sets.py --from-git-tree tree.json

The script will not overwrite a texture set that already references a normal,
heightmap, or image MERS. Those belong to later phases.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from constants import COLOR_EXTENSIONS, EXCLUDED_BLOCK_FILENAMES, UNIFORM_MERS, VANILLA_TAG

REPO = Path(__file__).resolve().parents[2]
PACK_BLOCKS = REPO / "development_resource_packs" / "Choice Textures_rp" / "textures" / "blocks"
LIST_PATH = Path(__file__).resolve().parent / f"vanilla_block_texture_sets_{VANILLA_TAG}.txt"
REPORT_PATH = Path(__file__).resolve().parent / "phase1_block_texture_set_report.json"


def load_vanilla_sets(list_path: Path) -> set[str]:
    lines = [line.strip().replace("\\", "/") for line in list_path.read_text(encoding="utf-8").splitlines()]
    return {line for line in lines if line and not line.startswith("#")}


def write_list_from_git_tree(tree_path: Path, list_path: Path) -> int:
    data = json.loads(tree_path.read_text(encoding="utf-8"))
    tree = data["tree"] if isinstance(data, dict) else data
    names = sorted(
        item["path"].replace("\\", "/")
        for item in tree
        if item.get("path", "").endswith(".texture_set.json")
    )
    header = (
        f"# Block texture sets in Mojang/bedrock-samples {VANILLA_TAG}\n"
        "# resource_pack/textures/blocks, paths relative to that folder.\n"
        "# Regenerated by generate_block_texture_sets.py --from-git-tree.\n"
    )
    list_path.write_text(header + "\n".join(names) + "\n", encoding="utf-8")
    return len(names)


def texture_set_text(stem: str) -> str:
    payload = {
        "format_version": "1.21.30",
        "minecraft:texture_set": {
            "color": stem,
            "metalness_emissive_roughness_subsurface": UNIFORM_MERS,
        },
    }
    return json.dumps(payload, indent=2) + "\n"


def is_hand_authored(path: Path) -> bool:
    if not path.exists():
        return False
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return True
    body = data.get("minecraft:texture_set")
    if not isinstance(body, dict):
        return True
    allowed = {"color", "metalness_emissive_roughness_subsurface"}
    if set(body) - allowed:
        return True
    mers = body.get("metalness_emissive_roughness_subsurface")
    if isinstance(mers, str):
        return True
    if "metalness_emissive_roughness" in body or "normal" in body or "heightmap" in body:
        return True
    return False


def iter_color_images(blocks: Path):
    seen: set[str] = set()
    for path in sorted(blocks.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix.lower() not in COLOR_EXTENSIONS:
            continue
        # Do not skip stems that end in _normal. Vanilla color names include
        # sandstone_normal, red_sandstone_normal, piston_top_normal, and
        # rail_normal. The vanilla texture-set list is what decides which
        # stems get a set; a real normal map is not on that list.
        rel_image = path.relative_to(blocks).as_posix()
        rel_set = str(Path(rel_image).with_suffix(".texture_set.json")).replace("\\", "/")
        if rel_set in seen:
            continue
        seen.add(rel_set)
        yield rel_image, rel_set, path.stem


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-git-tree", type=Path, help="GitHub git tree JSON for textures/blocks")
    parser.add_argument("--list", type=Path, default=LIST_PATH)
    parser.add_argument("--blocks", type=Path, default=PACK_BLOCKS)
    args = parser.parse_args()

    if args.from_git_tree:
        count = write_list_from_git_tree(args.from_git_tree, args.list)
        print(f"wrote {count} vanilla texture-set paths to {args.list}")

    if not args.list.exists():
        print(f"missing vanilla list: {args.list}", file=sys.stderr)
        return 1
    vanilla = load_vanilla_sets(args.list)
    if not vanilla:
        print("vanilla list is empty", file=sys.stderr)
        return 1

    written = []
    skipped_hand = []
    skipped_excluded = []
    unchanged = []
    without_vanilla = []

    for rel_image, rel_set, stem in iter_color_images(args.blocks):
        if rel_set not in vanilla:
            without_vanilla.append(rel_image)
            continue
        dest = args.blocks / rel_set
        if Path(rel_image).name in EXCLUDED_BLOCK_FILENAMES:
            skipped_excluded.append(rel_image)
            continue
        if is_hand_authored(dest):
            skipped_hand.append(rel_set)
            continue
        text = texture_set_text(stem)
        if dest.exists() and dest.read_text(encoding="utf-8") == text:
            unchanged.append(rel_set)
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text, encoding="utf-8")
            written.append(rel_set)

    report = {
        "vanilla_tag": VANILLA_TAG,
        "vanilla_block_texture_sets": len(vanilla),
        "generated": len(written) + len(unchanged),
        "written": len(written),
        "unchanged": len(unchanged),
        "choice_colors_without_vanilla_set": len(without_vanilla),
        "skipped_excluded": sorted(skipped_excluded),
        "skipped_hand_authored": sorted(skipped_hand),
        "uniform_mers": UNIFORM_MERS,
    }
    REPORT_PATH.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    if skipped_hand:
        print("left hand-authored texture sets alone:", file=sys.stderr)
        for name in skipped_hand:
            print(f"  {name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    raise SystemExit(main())
